const brandRe = new RegExp(
  `\\b(${BRANDS.map((b) => b.trim().replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})\\b`,
  'i',
);

/** Marka w nazwie: znana marka albo słowo pisane wielkimi literami (SR Legacy tak oznacza marki) */
export function isBranded(name: string): boolean {
  if (brandRe.test(name)) return true;
  // np. "KRAFT", "MCDONALD'S" - pomijamy skróty techniczne (USDA, NFS, UHT, NS)
  const caps = name.match(/\b[A-Z][A-Z'&.-]{2,}\b/g) ?? [];
  return caps.some((w) => !['USDA', 'NFS', 'UHT', 'NS', 'RTE', 'RTF', 'UPC', 'II', 'III'].includes(w));
}

/**
 * Warianty techniczne SR Legacy, które nie są osobnymi składnikami w kuchni
 * (części tuszy "separable fat", klasy jakości mięsa, przygotowania pod badania).
 */
const TECHNICAL = [
  /separable fat/i,
  /\bsubcutaneous\b/i,
  /\bseam fat\b/i,
  /\bvariety meats and by-products\b/i,
  /\bmechanically separated\b/i,
  /\bmeat only, cooked, (simmered|stewed)\b.*\bgiblets\b/i,
  /\bnot further specified\b/i,
  /\bwith added vitamin\b/i,
  /\bfortified\b/i,
  /\bindustrial\b/i,
  /\bfor (food service|restaurant|institutional)\b/i,
  /\bprepared from recipe\b/i,
  /\bpowder, prepared\b/i,
];

export function technicalVariant(food: SourceFood): boolean {
  return food.source === 'USDA' && TECHNICAL.some((re) => re.test(food.nameEn));
}

export function selectFood(food: SourceFood): RejectReason | null {
  if (food.source === 'CIQUAL' ? CIQUAL_EXCLUDED.has(food.group) : USDA_EXCLUDED.has(food.group)) {
    return 'GROUP_EXCLUDED';
  }
  if (food.source === 'USDA' && isBranded(food.nameEn)) return 'BRANDED';
  if (REQUIRED_NUTRIENTS.some((k) => food.values[k] === null)) return 'MISSING_REQUIRED';
  if (technicalVariant(food)) return 'TECHNICAL_VARIANT';
  return null;
}
